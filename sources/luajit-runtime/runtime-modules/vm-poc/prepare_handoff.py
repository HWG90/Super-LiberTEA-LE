"""Generate work/handoff_assets.h for the boot handoff (build 26088801).

Embeds the nine stock chunks (original PUC bytecode plus recovered source, for
exact-byte translation in LuaJIT) and the exact LLL boot source whose compiled
form is the installed boot resource f476df93691895fa (patch_94). The LLL source
must reproduce LLL's embedded stock boot byte for byte; both are checked here.
"""
from pathlib import Path
import hashlib,json,os,re

ROOT=Path(__file__).resolve().parent
STOCK=ROOT/'work'/'stock'
LLL=Path('/home/goose/Documents/ChatGPT/Linux HD2/native-work/cffi-pointerfix-current/runtime-source-fixed.lua')
LLL_SHA256='dc66664dedc4a5c8f42d8bd13a6d65d758f7a6b0a2dce189538b7aa453747fc7'
# Another LLL source for the handoff (e.g. lll-luajit/out: LLL's LuaJIT build), pinned by its SHA-256.
if os.environ.get('HD2_HANDOFF_LLL'):
    LLL,LLL_SHA256=Path(os.environ['HD2_HANDOFF_LLL']),os.environ['HD2_HANDOFF_LLL_SHA256']
NAMES={0x0d4816de1d4771f1:'core/animation/lua/runtime/animationflowcallbacks',
       0x19bc198a3e7bb327:'core/wwise/lua/wwise_bank_reference'}

def carray(name,data):
    rows=[','.join(str(b) for b in data[i:i+64]) for i in range(0,len(data),64)]
    return 'static const unsigned char %s[%d]={\n%s};'%(name,max(len(data),1),',\n'.join(rows) or '0')

def prepare():
    out=['/* Generated by prepare_handoff.py. */']
    rows=[];receipt={'stock':[],'lll':{}}
    for i,luac in enumerate(sorted(STOCK.glob('*.luac'))):
        ident=int(luac.stem,16);source=luac.with_suffix('.lua').read_bytes();original=luac.read_bytes()
        assert original[:12]==bytes.fromhex('1b4c75615100010404040800'),luac
        out.append(carray('h%d_source'%i,source));out.append(carray('h%d_original'%i,original))
        name=NAMES.get(ident,'stock/%016x'%ident)
        rows.append('{%s,h%d_source,%d,NULL,0,h%d_original,%d,0x%016xu},'%(json.dumps(name),i,len(source),i,len(original),ident))
        receipt['stock'].append({'id':'%016x'%ident,'source_sha256':hashlib.sha256(source).hexdigest(),'original_sha256':hashlib.sha256(original).hexdigest()})
    legacy=json.loads((ROOT/'work'/'legacy'/'LEGACY-RECEIPT.json').read_text())
    for j,entry in enumerate(legacy['entries']):
        code=(ROOT/'work'/'legacy'/entry['bytecode']).read_bytes();source=(ROOT/'work'/'legacy'/entry['source']).read_bytes()
        assert hashlib.sha256(code).hexdigest()==entry['bytecode_sha256'] and hashlib.sha256(source).hexdigest()==entry['source_sha256'],entry['name']
        assert code[:3]==b'\x1bLJ' and not code[4]&0x08,'legacy entry must be FR1 LuaJIT bytecode'
        out.append(carray('legacy%d_source'%j,source));out.append(carray('legacy%d_original'%j,code))
        rows.append('{%s,legacy%d_source,%d,NULL,0,legacy%d_original,%d,0},'%(json.dumps('legacy/'+entry['source']),j,len(source),j,len(code)))
        receipt.setdefault('legacy',[]).append({'name':entry['name'],'bytecode_sha256':entry['bytecode_sha256'],'source_sha256':entry['source_sha256']})
    body=LLL.read_bytes()
    assert hashlib.sha256(body).hexdigest()==LLL_SHA256,'LLL boot source changed'
    embedded=re.search(rb'loadstring\("((?:\\\d{3})+)","@stock_steam_boot"\)',body).group(1)
    stock_boot=bytes(int(x) for x in re.findall(rb'\\(\d{3})',embedded))
    assert stock_boot==(STOCK/'f476df93691895fa.luac').read_bytes(),'LLL embeds a different stock boot'
    out.append(carray('handoff_lll_source',body))
    out.append('static const HD2Asset handoff_assets[]={\n'+'\n'.join(rows)+'\n};')
    raw=Path('/home/goose/Projects/Linux HD2 Mods/builds/26568081/runtime/images/exe-26568081.bin').read_bytes()
    mapped=Path('/home/goose/Projects/Linux HD2 Mods/builds/26568081/runtime/images/exe-26568081.bin').read_bytes()
    getter=raw[0x9fc00:0x9fc00+109]
    assert getter==mapped[0x9fc00:0x9fc00+109] and getter.startswith(bytes.fromhex('4883ec284c8bd1'))
    out.append(carray('handoff_getter_witness',getter))
    # LLL under LuaJIT takes LLL_DISCOVERY_HASH or loads its own src/discovery_hash.lua
    # (an ffi/bit murmur64); the handoff defines the global from that exact file.
    discovery=Path('/home/goose/Documents/Codex/2026-10-22/a-2/work/LLL/src/discovery_hash.lua').read_bytes()
    out.append(carray('handoff_discovery_source',b'LLL_DISCOVERY_HASH=(function()\n'+discovery+b'\nend)()\n'))
    receipt['discovery_hash_sha256']=hashlib.sha256(discovery).hexdigest()
    out.append('#define HANDOFF_LLL_SIZE %du'%len(body))
    out.append('#define HANDOFF_LLL_SHA256 "%s"'%LLL_SHA256)
    (ROOT/'work'/'handoff_assets.h').write_text('\n'.join(out)+'\n')
    receipt['lll']={'path':str(LLL),'sha256':LLL_SHA256,'bytes':len(body),'embedded_stock_boot_matches':True}
    (ROOT/'work'/'handoff_assets.json').write_text(json.dumps(receipt,indent=1)+'\n')
    print(len(rows)-len(legacy['entries']),'stock and',len(legacy['entries']),'legacy chunks;',len(body),'LLL source bytes')

if __name__=='__main__':
    prepare()
