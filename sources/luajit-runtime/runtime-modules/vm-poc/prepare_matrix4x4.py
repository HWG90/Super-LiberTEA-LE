"""Regenerate Matrix4x4 callback and native helper witnesses for build 26088801.

Prefixes must be identical in the on-disk evidence image and the live mapped
capture. Callbacks on the 0x438000..0x439fff pages (uncommitted in the mapped
capture, packed on disk) come from a read-only in-game dump
(matrix4x4_page_dump.lua) that must equal the mapped capture wherever that
capture has code.
"""
from pathlib import Path
import hashlib,json

ROOT=Path(__file__).resolve().parent
RAW='/home/goose/Documents/ChatGPT/Linux HD2/native-work/evidence/exe-26088801.bin'
MAPPED='/home/goose/Documents/Codex/2026-10-22/a-2/work/ffi-comparison/current-mapped.bin'
# Public entries (some are thunks into shared bodies, listed separately).
ENTRIES={
    '__call':0x437140,'__call_body':0x436be0,'zero':0x4377c0,'identity':0x437930,'from_translation':0x437e50,
    'inverse':0x43a6c0,'element':0x43aba0,'set_element':0x43ae50,'axis':0x43b0d0,'set_axis':0x43b2d0,
    'translation':0x43b830,'set_translation':0x43b950,'rotation':0x43baf0,'set_rotation':0x43bea0,
    'set_rotation_body':0x43bc10,'scale':0x43c3b0,'scale_body':0x43bec0,'set_scale':0x43c940,'set_scale_body':0x43c3d0,
    'x':0x43cdc0,'y':0x43cf00,'z':0x43d040,'set_x':0x43d160,'set_y':0x43d270,'set_z':0x43d380,
    'forward':0x43d870,'up':0x43d9b0,'right':0x43daf0,'set_forward':0x43dc10,'set_up':0x43dd20,'set_right':0x43de30,
    'transform':0x43e170,'transform_without_translation':0x43e410,'copy':0x43e7b0,'equal':0x43e8c0,
    'is_valid':0x43fe20,'is_valid_for_physics':0x43fed0,'quaternion_from_matrix4x4':0x430a70,
}
ENTRIES.update({'multiply':0x43a590,'multiply_body':0x439f20,'from_quaternion':0x438250,'from_quaternion_body':0x437f80,
    'from_quaternion_position':0x438520,'from_quaternion_position_body':0x438270,'from_elements':0x438aa0,'from_elements_body':0x438540,
    'from_axes':0x438c90,'to_elements':0x439170,'to_string':0x439db0,'to_string_body':0x439330})
# Box callbacks (registered by hd2env_register_boxes; probed with the Matrix4x4 host).
ENTRIES.update({'quaternionbox_call':0x42fec0,'quaternionbox_call_body':0x42fc20,'quaternionbox_store':0x430150,
    'quaternionbox_store_body':0x42fee0,'quaternionbox_unbox':0x430210,
    'matrix4x4box_call':0x437290,'matrix4x4box_store':0x437460,'matrix4x4box_unbox':0x437560})
HELPERS={'matrix_inverse':0x66ca00,'matrix_rotation':0x66bfc0}
LIVE_DUMP=ROOT.parent/'live-load'/'2026-10-24'/'matrix4x4-code-0x437000.bin'
LIVE_FIRST=0x437000

def prepare():
    raw,mapped=Path(RAW).read_bytes(),Path(MAPPED).read_bytes()
    live=LIVE_DUMP.read_bytes();last=LIVE_FIRST+len(live)
    for at in range(0,len(live),16):
        row=mapped[LIVE_FIRST+at:LIVE_FIRST+at+16]
        assert not any(row) or row==live[at:at+16],hex(LIVE_FIRST+at)
    rows=[]
    for name,rva in list(ENTRIES.items())+list(HELPERS.items()):
        data=mapped[rva:rva+32]
        required=1
        if not any(data) and LIVE_FIRST<=rva and rva+32<=last:
            # Page is unpacked by the game on first execution; the port replaces this
            # callback and never calls it, so it may be unreadable at registration.
            assert name not in HELPERS,name
            data=live[rva-LIVE_FIRST:rva-LIVE_FIRST+32];required=0
        else:assert data==raw[rva:rva+32],name
        assert any(data),name
        rows.append('{0x%x,%d,{%s}}, /* %s */'%(rva,required,','.join(map(str,data)),name))
    body=['/* Generated by prepare_matrix4x4.py: 32-byte prefixes from verified captures. */',
          '/* required=0: checked only when the page is already resident. */',
          'static const struct {unsigned rva;int required;unsigned char bytes[32];} matrix4x4_witnesses[]={',*rows,'};']
    for name,rva in HELPERS.items():body.append('#define HD2_MATRIX4X4_%s 0x%xu'%(name.upper(),rva))
    out=ROOT/'work'/'matrix4x4_witnesses.h'
    out.write_text('\n'.join(body)+'\n')
    print(json.dumps({'witnesses':len(rows),'sha256':hashlib.sha256(out.read_bytes()).hexdigest()}))

if __name__=='__main__':prepare()
