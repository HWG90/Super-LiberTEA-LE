"""Regenerate Quaternion callback and native helper witnesses for build 26088801.

Each prefix must be identical in the on-disk evidence image and the live mapped
capture, so packed or not-yet-committed pages are never trusted as witnesses.
The 0x433000..0x435000 page pair is packed on disk and was uncommitted in the
mapped capture; it is taken from a read-only in-game dump (quaternion_page_dump.lua)
that must equal the mapped capture wherever that capture has code.
"""
from pathlib import Path
import hashlib,json

ROOT=Path(__file__).resolve().parent
CAPTURES={
    '/home/goose/Documents/ChatGPT/Linux HD2/native-work/evidence/exe-26088801.bin':None,
    '/home/goose/Documents/Codex/2026-10-22/a-2/work/ffi-comparison/current-mapped.bin':None,
}
LIVE_DUMP=ROOT.parent/'live-load'/'2026-10-24'/'quaternion-code-0x433000.bin'
LIVE_FIRST=0x433000
# Callback entries (from vm-trace/quaternion-callback-intake.json) followed by
# pure native helpers the replacement calls instead of re-deriving CRT math.
ENTRIES={
    '__call':0x42fa90,'identity':0x431b00,'axis_angle':0x431d00,'from_elements':0x4304a0,
    'multiply':0x4326e0,'norm':0x434970,'negate':0x434500,'equal':0x4329b0,'is_valid':0x436240,
    'to_elements':0x430e40,'set_xyzw':0x4362e0,
    'normalize':0x433110,'inverse':0x433400,'conjugate':0x433670,'dot':0x433850,'lerp':0x433920,'slerp':0x433c40,
    'rotate':0x435480,'forward':0x4358e0,'up':0x435be0,'right':0x435ed0,'angle':0x435130,
    'decompose':0x434ec0,'lerp_wrap':0x434130,'to_euler_angles_xyz':0x431110,
    'from_euler_angles_xyz':0x430720,'look':0x432080,'to_string':0x431320,
}
HELPERS={
    'atan2f':0x134f790,'asinf':0x134f4c0,'acosf':0x147b150,'sinf':0x134f170,
    'quaternion_from_euler_degrees':0x66be20,'quaternion_from_basis':0x66bc40,
}

def prepare():
    raw,mapped=[Path(p).read_bytes() for p in CAPTURES]
    live=LIVE_DUMP.read_bytes();last=LIVE_FIRST+len(live)
    for at in range(0,len(live),16):
        row=mapped[LIVE_FIRST+at:LIVE_FIRST+at+16]
        assert not any(row) or row==live[at:at+16],hex(LIVE_FIRST+at)
    rows=[]
    for name,rva in list(ENTRIES.items())+list(HELPERS.items()):
        data=mapped[rva:rva+32]
        required=1
        if not any(data) and LIVE_FIRST<=rva and rva+32<=last:
            # Page is unpacked by the game on first execution; the port replaces this
            # callback and never calls it, so it may be unreadable at registration.
            assert name not in HELPERS,name
            data=live[rva-LIVE_FIRST:rva-LIVE_FIRST+32];required=0
        else:assert data==raw[rva:rva+32],name
        assert any(data),name
        rows.append('{0x%x,%d,{%s}}, /* %s */'%(rva,required,','.join(map(str,data)),name))
    body=['/* Generated by prepare_quaternion.py: 32-byte prefixes from verified captures. */',
          '/* required=0: checked only when the page is already resident. */',
          'static const struct {unsigned rva;int required;unsigned char bytes[32];} quaternion_witnesses[]={',*rows,'};']
    for name,rva in HELPERS.items():
        body.append('#define HD2_QUATERNION_%s 0x%xu'%(name.upper(),rva))
    out=ROOT/'work'/'quaternion_witnesses.h'
    out.write_text('\n'.join(body)+'\n')
    print(json.dumps({'witnesses':len(rows),'sha256':hashlib.sha256(out.read_bytes()).hexdigest()}))

if __name__=='__main__':prepare()
