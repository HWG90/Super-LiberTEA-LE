"""Regenerate the engine resource resolver witness for the port's capture (26568081).

The 26251122 witness (work/resource_witness.h) is the resolver at 0x6321a0. On 26568081 the resolver is at
0x6321a0 (-0x70, the delta engine_resources.c already uses). Accept the new bytes only when the old witness is the
26251122 resolver exactly and the new function matches it with rel32 and RIP displacements masked; then write the header.
"""
import hashlib, json, re, sys
from pathlib import Path
ROOT = Path(__file__).resolve().parent
sys.path.insert(0, '/home/goose/.claude/skills/hd2-game-update/scripts')
import migrate_rvas as m
OLD_IMAGE = '/home/goose/Projects/Linux HD2 Mods/builds/26251122/runtime/images/exe-26251122.bin'
NEW_IMAGE = '/home/goose/Projects/Linux HD2 Mods/builds/26568081/runtime/images/exe-26568081.bin'
OLD_RVA, NEW_RVA = 0x6321a0, 0x632240
header = ROOT / 'work/resource_witness.h'
text = header.read_text()
blocks = re.findall(r'resource_witness\[\]\s*=\s*\{([^}]*)\}', text)
assert blocks, 'resource witness array not found'
old_bytes = bytes(int(x) for x in blocks[0].replace('\n', '').split(',') if x.strip())
old, new = m.Image(OLD_IMAGE), m.Image(NEW_IMAGE)
assert old.data[OLD_RVA:OLD_RVA + len(old_bytes)] == old_bytes, 'witness is not the 26251122 resolver'
assert m.body_identical(old, new, OLD_RVA, len(old_bytes), NEW_RVA), 'resolver changed beyond displacements'
fresh = new.data[NEW_RVA:NEW_RVA + len(old_bytes)]
header.write_text('/* Engine resource resolver at 0x%x (26568081), regenerated by prepare_resources.py. */\n'
                  'static const unsigned char resource_witness[]={%s};\n' % (NEW_RVA, ','.join(map(str, fresh))))
print(json.dumps({'bytes': len(fresh), 'old_sha256': hashlib.sha256(old_bytes).hexdigest()[:16],
                  'new_sha256': hashlib.sha256(fresh).hexdigest()[:16], 'masked_identical': True}))
