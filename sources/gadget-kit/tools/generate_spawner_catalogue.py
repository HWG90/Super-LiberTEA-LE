"""Generate src/spawner/catalogue.lua from the running game (read-only, through LLtM).

Rows start from Bridge Combat's validated support catalogue (names, backpack pairs, model unit
overrides) and are checked against the live armory catalogue: each weapon and backpack must
have an authored pickup definition (world+0xF146E0) and a loadout package. Support items in
the live catalogue that Bridge Combat does not list are added when they pass the same checks;
names come from the user-confirmed EXTRA_NAMES, else hd2_names, else the item id.
Usage: python3 -I tools/generate_spawner_catalogue.py   (game running, LLtM loaded)
"""
import json, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "src", "spawner", "catalogue.lua")
BRIDGE = "/home/goose/.config/hd2arsenal/mods/Bridge-Combat-CFFI-26088801/Payload/src/support_catalogue.lua"
sys.path.insert(0, "/home/goose/Documents/ChatGPT/GooseGadgets/relay-tools")
EXTRA_NAMES = {4146034362: "LAS-44 Nova"}

PROBE = r"""eval local H,I,L=use('hd2_addresses'),use('hd2_items'),use('hd2_load') local A=H.get()
local cat=assert(I.catalog(A)) local w=ptr(game+A.WORLD) local t=ptr(w+0xf146e0) local raw=read(t,0x4640)
local authored={} for i=0,0x463 do local k=raw:sub(i*16+1,i*16+8) if k~=string.rep('\0',8) then authored[hex(k:reverse())]=get(raw,i*16+8,'u32') end end
local rows={} local function row(kind,id,ty,name) local p=L.package_of(A,ty) rows[#rows+1]=table.concat({kind,id,ty,p and hex(p:reverse()) or '-',authored[ty] and tostring(authored[ty]) or '-',name or '-'},',') end
for _,r in ipairs(cat.records) do if r.kind==2 or r.kind==6 then row(r.kind,r.id,r.type,r.name) end end
for _,ty in ipairs({%s}) do row(0,0,ty,nil) end
return table.concat(rows,';')"""


def lua_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    from llm_host import llm
    src = open(BRIDGE).read()
    bridge = []
    for line in src.splitlines():
        m = re.search(r'\{name="([^"]+)",id=(\d+),kind=2,type="(\w+)"(?:,unit="(\w+)")?,package="(\w+)"(.*)', line)
        if not m:
            continue
        bp = re.search(r'backpack=\{name="([^"]+)",id=(\d+),kind=6,type="(\w+)",package="(\w+)"\}', m.group(6))
        bridge.append({"name": m.group(1), "id": int(m.group(2)), "type": m.group(3), "unit": m.group(4), "package": m.group(5),
                       "backpack": bp and {"name": bp.group(1), "id": int(bp.group(2)), "type": bp.group(3), "package": bp.group(4)}})
    extra = sorted({r["type"] for r in bridge} | {r["backpack"]["type"] for r in bridge if r["backpack"]})
    out = llm.run([(PROBE % ",".join("'%s'" % t for t in extra)).replace("\n", " ")], timeout=60)
    line = next(l for l in out.splitlines() if " = " in l).split(" = ", 1)[1].strip('"')
    info, catalog = {}, []
    for r in line.split(";"):
        kind, i, ty, pkg, auth, name = r.split(",", 5)
        info[ty] = {"package": None if pkg == "-" else pkg, "authored": auth != "-"}
        if kind != "0":
            catalog.append({"kind": int(kind), "id": int(i), "type": ty, "name": None if name in ("-", "nil") else name})
    rows, report = [], {"kept": [], "dropped": [], "added": []}

    def ok(item):
        live = info.get(item["type"], {})
        return live.get("authored") and live.get("package") == item["package"]

    for r in bridge:
        if ok(r) and (not r["backpack"] or ok(r["backpack"])):
            rows.append(r); report["kept"].append(r["name"])
        else:
            report["dropped"].append(r["name"])
    known = {r["id"] for r in bridge}
    for c in catalog:
        if c["kind"] != 2 or c["id"] in known:
            continue
        live = info[c["type"]]
        if not (live["authored"] and live["package"]):
            report["dropped"].append("%s (%d)" % (c["name"] or "unnamed", c["id"]))
            continue
        name = EXTRA_NAMES.get(c["id"]) or c["name"] or "Unidentified support %d" % c["id"]
        rows.append({"name": name, "id": c["id"], "type": c["type"], "unit": None, "package": live["package"], "backpack": None})
        report["added"].append(name)
    rows.sort(key=lambda r: r["name"].lower())
    lines = ["-- Generated by tools/generate_spawner_catalogue.py from the live game (game.dll 6AD7C05D):",
             "-- Bridge Combat's validated support rows plus live-catalogue additions. Every weapon and",
             "-- backpack below had an authored pickup definition and a matching loadout package.",
             "-- Do not edit by hand; regenerate after a game update.",
             "return {"]
    for r in rows:
        f = ["name=%s" % lua_str(r["name"]), "id=%d" % r["id"], "kind=2", 'type="%s"' % r["type"]]
        if r["unit"]:
            f.append('unit="%s"' % r["unit"])
        f.append('package="%s"' % r["package"])
        if r["backpack"]:
            b = r["backpack"]
            f.append('backpack={name=%s,id=%d,kind=6,type="%s",package="%s"}' % (lua_str(b["name"]), b["id"], b["type"], b["package"]))
        lines.append("    {" + ",".join(f) + "},")
    lines.append("}")
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    open(OUT, "w").write("\n".join(lines) + "\n")
    json.dump(report, open(os.path.join(os.path.dirname(OUT), "catalogue-report.json"), "w"), indent=1)
    print(len(rows), "rows;", json.dumps(report))


if __name__ == "__main__":
    main()
