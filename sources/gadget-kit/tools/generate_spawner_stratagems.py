"""Generate the fifth-slot catalogue from the build 26251122 descriptor capture.

The fixture records StratagemInfo's kind/id, debug and English loadout labels,
HUD type (+0xb8), selectable (+0x80) and active (+0xc0) flags, icon (+0xb0),
loadout package (+0xa8), and call-in code. Capture all rows, including services,
so selection can be checked independently of the Spawner support-weapon list.
"""
import csv
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
FIXTURE = ROOT / 'tools/fixtures/stratagems-26251122.csv'
GROUPS = {
    'EAGLE': 'Eagles', 'ORBITAL': 'Orbitals', 'TEAM WEAPONS': 'Weapons',
    'BACKPACK': 'Backpacks', 'SENTRYS': 'Turrets', 'SENTRIES': 'Turrets',
    'EMPLACEMENTS': 'Deployables', 'VEHICLES': 'Deployables',
}
# The silo is a deployable. The two station strikes and fly-by lack the usual
# type prefix. Keep the old picker's station and alternate Eagle entries.
GROUP_OVERRIDES = {
    'MiniMissile': 'Deployables', 'TurretTesla': 'Turrets', 'Nuke': 'Orbitals',
    'CarpetBomb': 'Eagles', 'EagleFlyBy': 'Eagles', 'OrbitalConfetti': 'Orbitals',
}


def pretty_enum(key):
    return re.sub(r'(?<=[a-z])(?=[A-Z])', ' ', key.replace('_', ' ')).strip()


def display_name(row, weapon):
    if row['enum'] == 'SniperRifleDuo':
        return 'AMW-20 Apex'
    if weapon and not weapon.startswith('Unidentified support'):
        return weapon
    label = row['english_name']
    if not label:
        return pretty_enum(row['enum'])
    return ' '.join(word if word in {'EMS', 'HE', 'HMG', 'FRV', 'MK', 'XVI', 'K-9', 'C4'}
                    else word.title().replace('Mm', 'mm').replace('Kg', 'kg') for word in label.split())


def main():
    catalogue = (ROOT / 'src/spawner/catalogue.lua').read_text()
    weapons = {int(i): name for name, i in re.findall(r'\{name="([^"]+)",id=(\d+),kind=2', catalogue)}
    # Support delivery already holds both the weapon and paired backpack package.
    held = {}
    for line in catalogue.splitlines():
        match = re.match(r'\s*\{name="[^"]+",id=(\d+),kind=2', line)
        if match:
            held[int(match[1])] = set(re.findall(r'package="([a-f0-9]{16})"', line))
    with FIXTURE.open(newline='') as f:
        definitions = list(csv.DictReader(f))
    assert [int(row['kind']) for row in definitions] == list(range(1, 154))
    rows = []
    for row in definitions:
        kind, item_id, hud = (int(row[key]) for key in ('kind', 'id', 'hud'))
        weapon = weapons.get(item_id) if hud == 2 else None
        legacy = hud == 0 or weapon is not None
        selectable = int(row['select_flags']) & 2 and int(row['active_flags']) & 1
        if not legacy and not (item_id and selectable and row['icon']):
            continue
        group = GROUP_OVERRIDES.get(row['enum']) or GROUPS[row['debug_name'].split('.')[0]]
        name = display_name(row, weapon)
        package = row['loadout_package']
        fields = [f'name={json.dumps(name)}', f'kind={kind}', f'id={item_id}', f'category={hud}',
                  'code={' + ','.join(row['code']) + '}', f'group={json.dumps(group)}']
        if weapon:
            fields.append(f'item={item_id}')
        # Existing strikes do not deliver held equipment. A weapon can require
        # both its pickup package and a distinct stratagem package (e.g. Apex).
        if package and hud != 0 and package not in held.get(item_id, ()):
            fields.append(f'package="{package}"')
        assert hud == 0 or weapon or package, f'Missing loadout package for {name}'
        # The first 57 indices are the previous flat picker/API order.
        old_label = weapon or pretty_enum(row['enum'])
        rows.append(((not legacy, old_label.lower() if legacy else name.lower()), fields))
    lines = ['-- Generated by tools/generate_spawner_stratagems.py for Steam build 26251122.', 'return {']
    lines.extend('    {' + ','.join(fields) + '},' for _, fields in sorted(rows))
    (ROOT / 'src/spawner/stratagems.lua').write_text('\n'.join([*lines, '}', '']))
    print(f'{len(rows)} fifth-slot stratagems')


if __name__ == '__main__':
    main()
