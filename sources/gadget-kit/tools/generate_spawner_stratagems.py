"""Generate src/spawner/stratagems.lua: the stratagems the Spawner can add as a fifth mission slot.

Inputs (captured read-only on game.dll 6AD7C05D): native-work/stratagem-catalog-live.json (kind,
id, category, code) and native-work/stratagem-enum-migration.json (kind names). Included:
- category 0 (orbital and eagle strikes): deliver nothing held, so no package is needed;
- category 2 stratagems whose id is a Spawner support catalogue item: the weapon's package is
  loaded through the support path before the slot is added.
Turrets, mines, vehicles, drones and backpacks without a catalogue item are left out until their
packages are known. Usage: python3 -I tools/generate_spawner_stratagems.py
"""
import json, os, re

HERE = os.path.dirname(os.path.abspath(__file__))
WORK = "/home/goose/Documents/ChatGPT/Linux HD2/native-work"
OUT = os.path.join(HERE, "..", "src", "spawner", "stratagems.lua")


def pretty(name):
    name = name.replace("_", " ")
    return re.sub(r"(?<=[a-z])(?=[A-Z])", " ", name).strip()


def main():
    defs = json.load(open(os.path.join(WORK, "stratagem-catalog-live.json")))["definitions"]
    names = {v["kind"]: v["name"] for v in json.load(open(os.path.join(WORK, "stratagem-enum-migration.json")))["current"]}
    support = {int(i): n for n, i in re.findall(r'\{name="([^"]+)",id=(\d+),kind=2', open(os.path.join(HERE, "..", "src", "spawner", "catalogue.lua")).read())}
    rows = []
    for d in defs:
        if d["category"] == 0:
            rows.append((pretty(names[d["kind"]]), d, None))
        elif d["category"] == 2 and d["id"] in support:
            rows.append((support[d["id"]], d, d["id"]))
    rows.sort(key=lambda r: r[0].lower())
    lines = ["-- Generated by tools/generate_spawner_stratagems.py from stratagem-catalog-live.json (game.dll",
             "-- 6AD7C05D). item: the Spawner support catalogue id whose package must be resident first.",
             "-- Do not edit by hand.", "return {"]
    for name, d, item in rows:
        lines.append("    {name=%s,kind=%d,id=%d,category=%d,code={%s}%s}," % (
            json.dumps(name), d["kind"], d["id"], d["category"], ",".join(map(str, d["code"])), ",item=%d" % item if item else ""))
    lines.append("}")
    open(OUT, "w").write("\n".join(lines) + "\n")
    print(len(rows), "stratagems:", sum(1 for r in rows if r[2]), "with a support item")


if __name__ == "__main__":
    main()
