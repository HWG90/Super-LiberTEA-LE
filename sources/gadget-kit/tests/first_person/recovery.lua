local R=dofile(assert(NATIVE_ADS_TEST_ROOT)..'/src/first_person/recovery.lua')
local pass=0
local function test(name,fn)local ok,e=pcall(fn);assert(ok,name..': '..tostring(e));pass=pass+1 end
local proof={fresh=true,safe=true,same_player=true,foreign=false}
local read={failure_kind='temporary_read',failure_native_error=3}
test('only typed read failures with every positive proof authorize retry',function()
 assert(R.classify('camera',read,true,proof)=='retry')
 for _,key in ipairs({'fresh','safe','same_player'})do
  local p={fresh=true,safe=true,same_player=true,foreign=false};p[key]=false
  assert(R.classify('camera',read,true,p)=='fatal')
 end
 assert(R.classify('camera',read,true,{fresh=true,safe=true,same_player=true,foreign=true})=='fatal')
 assert(R.classify('camera',{error=3},true,proof)=='fatal','Old stats are not a fresh typed failure')
 assert(R.classify('camera',{failure_kind='temporary_read',failure_native_error=5},true,proof)=='fatal')
 assert(R.classify('camera',{failure_kind='temporary_read',failure_native_error=7},true,proof)=='fatal')
 assert(R.classify('camera',{failure_kind='temporary_read',failure_native_error=8},true,proof)=='fatal')
end)
test('unknown optional faults disable only their feature after cleanup',function()
 local r=R.new();local row=r:failure('blur',{},true,proof,10,'Unknown optional failure')
 assert(row.phase=='unavailable'and r:action('blur',100)=='unavailable')
 assert(not r:blocks_view(100))
 assert(R.classify('movement',{},false,proof)=='cleanup')
end)
test('pending cleanup never permits update or starts backoff',function()
 local r=R.new();r:failure('camera',read,false,proof,0,'read fault')
 assert(r:action('camera',100)=='cleanup'and r:blocks_view(100))
 assert(not r:cleanup('camera',false,100))
 assert(r:action('camera',1000)=='cleanup')
 assert(r:cleanup('camera',true,1000))
 assert(r:action('camera',1000.1)=='wait')
 assert(r:action('camera',1000.25)=='update')
end)
test('repeated faults have finite paced attempts and cannot reset with empty success',function()
 local r=R.new({max_attempts=3,base_delay=.25,max_delay=1})
 r:failure('fov',read,true,proof,0)
 assert(r:action('fov',.249)=='wait')
 assert(r:action('fov',.25)=='update');r:success('fov',.25,false)
 r:failure('fov',read,true,proof,.25)
 assert(r:action('fov',.749)=='wait');assert(r:action('fov',.75)=='update')
 local last=r:failure('fov',read,true,proof,.75)
 assert(last.phase=='exhausted'and r:action('fov',1e6)=='exhausted')
 assert(r:blocks_view(1e6))
end)
test('stable owned recovery clears episode but flapping does not',function()
 local r=R.new();r:failure('camera',read,true,proof,0)
 r:action('camera',.25);r:success('camera',.25,true)
 assert(r:snapshot().policies.camera.attempts==1)
 r:failure('camera',read,true,proof,.5);assert(r:snapshot().policies.camera.attempts==2)
 r:action('camera',1);r:success('camera',1,true);r:success('camera',3,true)
 assert(r:snapshot().policies.camera==nil)
end)
test('unknown core errors never gain retry authority from message text',function()
 local r=R.new();r:failure('camera',{},true,proof,0,'READ_FAILED temporary error3')
 assert(r:action('camera',100)=='fatal'and r:blocks_view(100))
 r:reset();assert(r:action('camera',100)=='update')
end)
test('status cannot mutate policy',function()
 local r=R.new();r:failure('blur',{},false,proof,0)
 local s=r:snapshot();s.policies.blur.phase='healthy';s.policies.camera={phase='healthy'}
 assert(r:action('blur',99)=='cleanup')
end)
test('read-free predicates request proof only for an actual retry',function()
 local r=R.new();assert(not r:has_policies()and not r:needs_proof('camera'))
 r:failure('camera',read,true,proof,0)
 assert(r:has_policies()and not r:needs_proof('camera'))
 assert(r:action('camera',.1)=='wait'and not r:needs_proof('camera'))
 assert(r:action('camera',.25)=='update'and r:needs_proof('camera'))
 local before=r:snapshot().policies.camera.phase
 for _=1,10 do assert(r:has_policies()and r:needs_proof('camera'))end
 assert(r:snapshot().policies.camera.phase==before,'Predicates must not advance retry state')
 assert(not r:revalidate('camera',{},.25)and not r:needs_proof('camera'))
 assert(r:action('camera',.5)=='update'and r:needs_proof('camera'))
 assert(r:revalidate('camera',proof,.5));r:success('camera',.5,true)
 assert(r:has_policies()and not r:needs_proof('camera'))
 r:success('camera',2.5,true);assert(not r:has_policies())
end)
print('Classified presentation recovery: '..pass..' cases passed')
-- A proof sampled before cleanup cannot grant authority to a later player.
do
 local r=R.new();r:failure('camera',read,true,proof,0)
 assert(r:action('camera',.25)=='update')
 assert(not r:revalidate('camera',{fresh=true,safe=true,same_player=false,foreign=false},.25))
 assert(r:blocks_view(.3))
 assert(r:action('camera',.5)=='update');assert(r:revalidate('camera',proof,.5))
 r:failure('camera',read,true,proof,1);assert(r:action('camera',2)=='update')
 assert(not r:revalidate('camera',{},12))
 assert(r:action('camera',100)=='exhausted')
 print('Fresh post-cleanup retry authorization and finite proof wait passed')
end

do
 local r=R.new();r:failure('blur',{failure_kind='unsafe',failure_native_error=5},true,proof,0)
 r:failure('camera',read,true,proof,0);r:owner_reset()
 assert(r:action('blur',100)=='unavailable'and r:action('camera',100)=='update')
 r:reset();assert(r:action('blur',100)=='update')
 print('New-body retirement never retries unknown/signature-failed optional policies')
end
