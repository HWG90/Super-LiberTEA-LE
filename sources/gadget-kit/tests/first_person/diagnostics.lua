local D=dofile(assert(NATIVE_ADS_TEST_ROOT)..'/src/first_person/diagnostics.lua')
local pass=0
local function test(name,fn)local ok,e=pcall(fn);assert(ok,name..': '..tostring(e));pass=pass+1 end
test('bounded chronological scalar snapshots',function()
 local d=D.new({capacity=16});local live={enabled=true,player='p',weapon='a',request=1,camera_kind=6,unsafe={}};live.loop=live
 for i=1,21 do live.time=i;assert(d:record(i,live))end
 live.player='changed'
 local s=d:snapshot();assert(s.count==16 and s.counters.overwritten==5)
 assert(s.frames[1].frame==6 and s.frames[16].frame==21)
 assert(s.frames[16].player=='p'and s.frames[16].unsafe==nil and s.frames[16].loop==nil)
 s.frames[1].player='mutation';s.counters.frames=999
 assert(d:snapshot().frames[1].player=='p'and d:snapshot().counters.frames==21)
end)
test('duplicate and stale Update frames cannot masquerade as new observations',function()
 local d=D.new();assert(d:record(2,{}));assert(not d:record(2,{}));assert(not d:record(1,{}))
 assert(not d:record(2.1,{}));assert(not d:record(0,{}))
 local c=d:snapshot().counters;assert(c.frames==1 and c.duplicate_frames==1 and c.out_of_order_frames==1)
end)
test('legitimate Photo editor and recovery handoffs are not view drops',function()
 local d=D.new();d:record(1,{pin_expected=true,pinned=false,foreign=true})
 d:record(2,{pin_expected=true,pinned=false,editor=true})
 d:record(3,{pin_expected=true,pinned=false,recovering=true})
 d:record(4,{pin_expected=true,pinned=false});d:record(5,{pinned=false})
 assert(d:snapshot().counters.unexpected_view_frames==1)
end)
test('turnover and interrupted transition counters remain distinct',function()
 local d=D.new()
 d:record(1,{player='p',weapon='a',request=1,camera_kind=6,transition_epoch=1,transition_progress=.3})
 d:record(2,{player='p',weapon='b',request=2,camera_kind=4,transition_epoch=2,transition_progress=0,cleanup_pending=true})
 d:record(3,{player='q',weapon='b',request=3,camera_kind=4,transition_epoch=3,transition_progress=1})
 local c=d:snapshot().counters
 assert(c.player_changes==1 and c.weapon_changes==1 and c.request_changes==2 and c.camera_changes==1)
 assert(c.transition_restarts==2 and c.cleanup_frames==1)
end)
test('native look duplicate detection requires positive repeated integration',function()
 local d=D.new()
 d:record(1,{enabled=true,look_sequence=10,look_samples=5})
 d:record(2,{enabled=true,look_sequence=10,look_samples=5}) -- normal held input: not a duplicate
 d:record(3,{enabled=true,look_sequence=10,look_samples=6})
 d:record(4,{enabled=true,look_sequence=10,look_samples=7,editor=true})
 assert(d:snapshot().counters.look_duplicates==1)
end)
test('rig and lens epochs can be compared without camera phase publication',function()
 local d=D.new()
 d:record(1,{camera_retired=true,pin_expected=false,pinned=false,fov_epoch=8,pose_epoch=8})
 d:record(2,{camera_retired=true,pin_expected=false,pinned=false,fov_epoch=9,pose_epoch=8})
 local s=d:snapshot()
 assert(s.frames[1].camera_retired==true and s.frames[1].camera_epoch==nil)
 assert(s.counters.mixed_publication_frames==1 and s.counters.unexpected_view_frames==0)
end)
test('native view diagnostics distinguish an expected fallback from a view drop',function()
 local d=D.new()
 d:record(1,{view_expected=true,view_visible=true})
 d:record(2,{view_expected=true,view_visible=false,recovering=true})
 d:record(3,{view_expected=true,view_visible=false,foreign=true})
 d:record(4,{view_expected=false,view_visible=false})
 d:record(5,{view_expected=true,view_visible=false})
 assert(d:snapshot().counters.unexpected_view_frames==1)
end)
test('failure events are bounded and invalid values cannot leak into snapshots',function()
 local d=D.new({capacity=16})
 for i=1,20 do d:event(i,'fault',{policy='blur',reason=string.rep('x',300),fov_applied=0/0,request=function()end})end
 local s=d:snapshot();assert(s.count==16 and s.counters.events==20 and s.counters.overwritten==4)
 assert(#s.frames[1].reason==200 and s.frames[1].request==nil and s.frames[1].fov_applied==nil)
 d:clear();assert(d:snapshot().count==0 and d:snapshot().counters.events==0)
end)
print('Bounded presentation diagnostics: '..pass..' cases passed')
