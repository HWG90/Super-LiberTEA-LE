-- Real Session/Heat/Memory/Policy, sparse native bytes and shared Core DTO.
local Fixture = assert(loadfile("tests/sampling_fixture.lua"))()
local checks = 0
local function eq(actual, expected, why)
    checks = checks + 1
    assert(actual == expected, (why or "different") .. ": " .. tostring(actual) .. " ~= " .. tostring(expected))
end
local f = Fixture.new()
local Policy = f.context.require("hud/policy.lua")
local policy, settings = Policy.new(), { get = function() end }
for _, case in ipairs({ { 0, 0, "0%" }, { 75, 0.5, "50%" }, { 150, 1, "100%" }, { 180, 1, "100%" } }) do
    local model = f:heat_sample(case[1], 150)
    eq(model.known, true, f.sampler.reason)
    eq(model.weapon.known, true)
    eq(model.weapon.ammo_kind, "heat")
    eq(model.weapon.heat_weapon, true)
    eq(model.weapon.heat, case[2])
    eq(model.weapon.heat_limit, 150)
    eq(model.weapon.heat_current, case[1])
    eq(model.weapon.count, nil)
    eq(model.weapon.reserve, nil)
    eq(model.weapon.count_kind, "heat")
    local view = policy:update(model, settings, 0.016)
    eq(view.weapon.text, case[3])
    eq(view.weapon.kind, "heat")
    eq(view.reload.visible, false)
end
-- Native entity-keyed overrides supersede a resource default; 100 is no assumed capacity.
local override = f:heat_sample(40, 80, true)
eq(override.weapon.heat, 0.5)
eq(override.weapon.heat_limit, 80)
local live = f:heat_sample(92.789604187012, 150)
eq(math.abs(live.weapon.heat - 92.789604187012 / 150) < 1e-10, true, "live Sickle calibration uses native150 limit")
eq(policy:update(live, settings, 0.016).weapon.text, "62%")
f:heat_sample(40, 80, true)
f.put(f.heat_runtime + 8, "\1")
override = f:sample()
eq(override.weapon.heat_locked, true)
local locked = policy:update(override, settings, 0.016)
eq(locked.weapon.tone, "yellow")
eq(locked.reload.visible, false)
-- Missing/invalid calibration remains a known heat type with unknown quantity,
-- never the native panel's misleading zero round count.
for _, bad_limit in ipairs({ 0, -1, 1e7, math.huge, 0 / 0 }) do
    local model = f:heat_sample(0, bad_limit, true)
    eq(model.known, true)
    eq(model.weapon.heat_weapon, true)
    eq(model.weapon.heat, nil)
    eq(model.weapon.count, nil)
    local view = policy:update(model, settings, 0.016)
    eq(view.weapon.text, nil)
    eq(view.reload.visible, false)
end
local model = f:heat_sample(75, 150)
local build = f.context.require("sampling/build.lua")
f.put(f.backend.base + build.heat_witnesses[1].at, "\0")
model = f:sample()
eq(model.weapon.heat, nil, "changed native calibration witness refuses sample")
eq(model.weapon.heat_weapon, true)
eq(model.weapon.count, nil)
f:heat_sample(75, 150)
f.pointer(0x57001000, f.actor_record)
model = f:sample()
eq(model.weapon.heat, nil, "heat component owner must match current weapon record")
f:heat_sample(75, 150)
f.uint(f.heat + 0x14, 0)
model = f:sample()
eq(model.weapon.heat, nil, "component index must be live")
f:heat_sample(75, 150)
f.before_read = function(at)
    if at == f.heat_config + 0x60 then
        f.uint(f.inventory_row, 91)
        f.uint(f.selector_row, 91)
    end
end
model = f:sample()
eq(model.weapon.heat, nil, "held identity is rechecked after calibration reads")
f.before_read = nil
f.uint(f.inventory_row, 90)
f.uint(f.selector_row, 90)
f:heat_sample(75, 150)
f.put(f.heat_runtime + 8, "\2")
model = f:sample()
eq(model.weapon.heat, nil, "unknown lock state is not a calibrated heat sample")
f:heat_sample(75, 150)
f.info.ammo_kind = "rounds"
model = f:sample()
eq(model.weapon.heat_weapon, nil)
eq(model.weapon.heat, nil)
eq(model.weapon.count, 31, "heat component existence never classifies a normal weapon")
eq(model.weapon.count_kind, "ammo")
-- Preserve the original explicitly named mixed-round/heat Talon exception.
model = f:heat_sample(60, 150, false, "416d053372c4e433", "rounds")
eq(model.weapon.ammo_kind, "heat")
eq(model.weapon.heat_weapon, true)
eq(model.weapon.heat, 0.4)
eq(model.weapon.count, nil)
eq(policy:update(model, settings, 0.016).weapon.text, "40%")
model = f:heat_sample(0, 150, false, "416d053372c4e433", "rounds")
eq(policy:update(model, settings, 0.016).weapon.text, "0%")
eq(policy.view.reload.visible, false)
model = f:heat_sample(0, 0, false, "416d053372c4e433", "rounds")
eq(model.weapon.heat_weapon, true)
eq(model.weapon.heat, nil)
eq(model.weapon.count, nil)
eq(policy:update(model, settings, 0.016).reload.visible, false)
f.uint(f.heat + 0x14, 0)
model = f:sample()
eq(model.weapon.heat_weapon, nil, "Talon exception requires its live owned heat component")
eq(model.weapon.ammo_kind, "rounds")
eq(model.weapon.count, 31)
model = f:heat_sample(60, 150, false, "27ee1ed8f6fb6356", "rounds")
eq(model.weapon.heat_weapon, nil, "a non-Talon round weapon is never reclassified from component presence")
eq(model.weapon.count, 31)
f.info.ammo_kind = nil
f.info.reloadable = false
model = f:sample()
eq(model.weapon.heat_weapon, nil, "nonreloadable is not a heat discriminator")
f:heat_sample(75, 150)
f.uint(f.panel + f.n.hud_self_last_slot, f.n.throwable_slot)
model = f:sample()
eq(model.weapon.heat_weapon, nil)
eq(model.weapon.throwing, true)
eq(model.weapon.count, 4)
eq(model.weapon.count_kind, "throwable")
eq(f.sampler:close(), true)
print("native heat sampling: " .. checks .. " checks passed")
